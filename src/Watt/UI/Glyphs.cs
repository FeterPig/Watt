using Watt.Models;

namespace Watt.UI
{
    /// <summary>
    /// Segoe Fluent Icons code points. Windows 11 ships "Segoe Fluent Icons"
    /// (C:\Windows\Fonts\SegoeIcons.ttf) whose glyphs are the same file-system-native line art the
    /// shell uses, so the panel does not need to ship any raster icons or font files of its own.
    ///
    /// Every value below was rendered with WPF at the panel's real 20 px size on the light (#FFFFFF)
    /// and dark (#1D1D20) surfaces and checked visually - see watt/assets/previews/glyphs-*.png and
    /// watt/docs/icons.md. The tray/app icons are *not* these glyphs: they are custom vector art
    /// generated by watt/tools/IconGen, so the app looks identical no matter how the font rasterizes.
    /// </summary>
    public static class Glyphs
    {
        public const string FontFamily = "Segoe Fluent Icons";

        public const string Keyboard = "\uE92E";   // KeyboardStandard
        public const string Mouse = "\uE962";      // Mouse
        public const string Headphone = "\uE7F6";  // Headphone (over-ear; E95B is the headset with mic boom)
        public const string Other = "\uE772";      // Devices (laptop + phone) for unknown peripherals
        public const string Bolt = "\uE945";       // LightningBolt (charging indicator)
        public const string Bluetooth = "\uE702";  // Bluetooth
        public const string Battery = "\uE83F";    // Battery10 (generic battery glyph)

        public static string ForKind(DeviceKind kind)
        {
            switch (kind)
            {
                case DeviceKind.Keyboard: return Keyboard;
                case DeviceKind.Mouse: return Mouse;
                case DeviceKind.Headphone: return Headphone;
                default: return Other;
            }
        }
    }
}
